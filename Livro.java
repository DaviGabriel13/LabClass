public class Livro {
    String nome;
    String autor;
    int ano;
    String descricao;
    int preco;

    public Livro(String nome, String autor, int ano, String descricao, int preco) {
        this.nome = nome;
        this.autor = autor;
        this.ano = ano;
        this.descricao = descricao;
        this.preco = preco;
    }
}